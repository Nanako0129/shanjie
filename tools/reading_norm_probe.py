#!/usr/bin/env python3
"""The in-context probe of the reading term's syllable normalisation (docs/spec/decoder.md §5, docs/spec/evaluation.md): eval/dev/reading-norm/context.txt.

For each (character c, reading r) pair the normalisation changes (core/tests/fixtures/reading-norm-pins.tsv: the rows of `shanjie-eval
--dump-reading-table` that differ from the table before the rule, which core/tests/reading_mass.rs pins), the bigram model's most frequent kept
pairs (v, c) and (c, w) with a count of at least 100, at most 10 on each side by (count, word) descending, v and w being words of the base lexicon
`mcbpmf-data.txt` read with their highest-scoring reading there (the first such row on a tie). Rows `|v c|reading(v) r` then `|c w|r reading(w)`
per pair, pairs sorted by (character, reading). c is the only counted single character of syllable r, so the synthetic answer of a row is that the
syllable typed there means c. The same inputs give the same bytes.

    python3 tools/reading_norm_probe.py            # rewrites eval/dev/reading-norm/context.txt
    python3 tools/reading_norm_probe.py --out FILE
    python3 tools/reading_norm_probe.py --check    # writes nothing; exit 1 unless the file already has exactly these bytes (make test-python)
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "reference", "proto"))
import lm as L  # noqa: E402

MIN_COUNT = 100  # a neighbour pair the model saw at least this often
PER_SIDE = 10    # neighbours kept before and after the character


def rows(pairs_text, base_text, model):
    changed = sorted(tuple(l.split("\t")[:2]) for l in pairs_text.splitlines() if l and not l.startswith("#"))
    best = {}
    for l in base_text.splitlines(keepends=True):
        p = l.split()
        if l[0] in "#_" or len(p) != 3 or len(p[1]) != len(p[0].split("-")):
            continue
        if p[1] not in best or float(p[2]) > best[p[1]][0]:
            best[p[1]] = (float(p[2]), p[0].split("-"))
    out = []
    for c, r in changed:
        if c not in model.ids:
            continue
        cid = model.ids[c]
        left = sorted(((ent.get(cid, 0), model.vocab[v]) for v, (_, _, ent) in model.ctx.items() if v >= 2 and ent.get(cid, 0) >= MIN_COUNT and model.vocab[v] in best), reverse=True)[:PER_SIDE]
        right = sorted(((n, model.vocab[w]) for w, n in model.ctx.get(cid, (0, 0, {}))[2].items() if w >= 2 and n >= MIN_COUNT and model.vocab[w] in best), reverse=True)[:PER_SIDE]
        out += [f"|{v}{c}|{' '.join(best[v][1])} {r}\n" for _, v in left]
        out += [f"|{c}{w}|{r} {' '.join(best[w][1])}\n" for _, w in right]
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pairs", default=os.path.join(ROOT, "core", "tests", "fixtures", "reading-norm-pins.tsv"))
    ap.add_argument("--base", default=os.path.join(ROOT, "data", "lexicon", "mcbpmf-data.txt"))
    ap.add_argument("--lm", default=os.path.join(ROOT, "data", "lm", "bigram.sjlm"))
    ap.add_argument("--out", default=os.path.join(ROOT, "eval", "dev", "reading-norm", "context.txt"))
    ap.add_argument("--check", action="store_true", help="write nothing; fail unless --out already holds the generated bytes")
    a = ap.parse_args()
    out = rows(open(a.pairs, encoding="utf-8").read(), open(a.base, encoding="utf-8").read(), L.BigramLM(a.lm, classes=False))
    if a.check:
        if "".join(out).encode() != open(a.out, "rb").read():
            sys.exit(f"{a.out} is not what tools/reading_norm_probe.py generates from the lexicon, the model and the pin file")
        print(f"{a.out}: {len(out)} rows, up to date")
        return
    with open(a.out, "w", encoding="utf-8") as f:
        f.writelines(out)
    print(f"{len(out)} rows -> {a.out}")


if __name__ == "__main__":
    main()
